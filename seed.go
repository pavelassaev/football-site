package main

import "fmt"

// seedClubs заполняет базу клубами КПЛ, если таблица пустая
func seedClubs() {
	var count int
	db.QueryRow("SELECT COUNT(*) FROM clubs").Scan(&count)
	if count > 0 {
		fmt.Println("Клубы уже есть, пропускаем заполнение")
		return
	}

	clubs := [][]interface{}{
		{"Кайрат", "Алматы", "Центральный стадион", 10, 8, 1, 1, 24, 8, 25},
		{"Астана", "Астана", "Астана Арена", 10, 7, 2, 1, 20, 9, 23},
		{"Тобол", "Костанай", "Центральный стадион", 10, 6, 2, 2, 18, 11, 20},
		{"Актобе", "Актобе", "Центральный стадион", 10, 5, 3, 2, 15, 10, 18},
		{"Ордабасы", "Шымкент", "Кажымукан", 10, 4, 3, 3, 13, 12, 15},
		{"Тараз", "Тараз", "Центральный стадион", 10, 3, 4, 3, 11, 13, 13},
		{"Атырау", "Атырау", "Мунайши", 10, 2, 3, 5, 9, 16, 9},
		{"Туран", "Туркестан", "Туркестан Арена", 10, 1, 2, 7, 7, 20, 5},
	}

	for _, c := range clubs {
		_, err := db.Exec(
			"INSERT INTO clubs (name, city, stadium, played, wins, draws, losses, goals_for, goals_against, points) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
			c[0], c[1], c[2], c[3], c[4], c[5], c[6], c[7], c[8], c[9],
		)
		if err != nil {
			fmt.Println("Ошибка вставки клуба:", err)
		}
	}
	fmt.Println("База заполнена клубами КПЛ")
}

